ALTER TABLE public.clinics ADD COLUMN IF NOT EXISTS settings_version INT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    family_id UUID NOT NULL,
    clinic_id BIGINT NOT NULL REFERENCES public.clinics(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    family_expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP NULL,
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS idx_refresh_tokens_family ON public.refresh_tokens(family_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_clinic_user ON public.refresh_tokens(clinic_id, user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expires_at ON public.refresh_tokens(expires_at);
